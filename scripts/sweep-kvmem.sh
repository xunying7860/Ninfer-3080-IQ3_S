#!/bin/bash
# KVMem 吞吐最优点扫荡（窗口轴 + 检索预算轴）
# 固定：CTX=262144（超长逻辑上下文）· SPEC=dflash2 DRAFT=12 · HOSTKV=16384 · rk4v4 · 采样用户定案
# 变量：
#   kvB  WINDOW=32768 RETRIEVE=8192  POOL=34304（536 页）  ← 常驻窗口放大
#   kvC  WINDOW=8192  RETRIEVE=8192  POOL=9728 （152 页）  ← 常驻窗口压小
#   kvD  WINDOW=16384 RETRIEVE=16384 POOL=17920（280 页）  ← 检索预算放大
# 每臂跑 65K 与 195K 两档（含长上下文 decode 512 与复用追问），再取引擎权威行。
set -uo pipefail
ROOT=/data/ninfer-fusion-kvmem
cd "$ROOT"
export SIZES="3100 9300"

./scripts/arm-kv.sh kvB NINFER_KV_WINDOW=32768 NINFER_KV_RETRIEVE=8192 NINFER_KV_RING=1 NINFER_HOST_PAGEABLE=1 NINFER_KV_REUSE_HOSTBACKED=1 POOL=34304 CTX=262144 HOSTKV=16384 SPEC=dflash2 DRAFT=12 LMHEAD=1 ADAPTIVE=0 DSS=1 VISION=1
./scripts/arm-kv.sh kvC NINFER_KV_WINDOW=8192 NINFER_KV_RETRIEVE=8192 NINFER_KV_RING=1 NINFER_HOST_PAGEABLE=1 NINFER_KV_REUSE_HOSTBACKED=1 POOL=9728 CTX=262144 HOSTKV=16384 SPEC=dflash2 DRAFT=12 LMHEAD=1 ADAPTIVE=0 DSS=1 VISION=1
./scripts/arm-kv.sh kvD NINFER_KV_WINDOW=16384 NINFER_KV_RETRIEVE=16384 NINFER_KV_RING=1 NINFER_HOST_PAGEABLE=1 NINFER_KV_REUSE_HOSTBACKED=1 POOL=17920 CTX=262144 HOSTKV=16384 SPEC=dflash2 DRAFT=12 LMHEAD=1 ADAPTIVE=0 DSS=1 VISION=1
echo "### 扫荡结束"
